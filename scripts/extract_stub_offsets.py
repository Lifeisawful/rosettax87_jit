#!/usr/bin/env python3
"""
Extract runtime_entry stub offsets from a built libRuntimeRosettax87.

The IDA trace loader labels the rt_routines segment using a table of
(offset, size, name) triples.  Its built-in table describes the *reference*
Rosetta runtime's stub page.  We map our own runtime_entry.S blob over that
region, and our layout differs for most stubs (86 of 98 at the time of writing)
plus adds xrstor/xsave — so the reference table mislabels almost everything when
analysing a trace produced by our runtime.

This script reads the symbol table of the linked image and emits the same triple
format, keyed on offsets from _stub_far_jmp (the blob base, which is what the
runtime-routines region is a verbatim copy of).

Sizes are derived from the gap to the next symbol in address order.  runtime_entry.S
packs stubs contiguously with no padding, so that gap is the stub's extent.

Usage:
  scripts/extract_stub_offsets.py [binary] [-o output.json]

Defaults to build/bin/libRuntimeRosettax87 and writes JSON to stdout.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path


DEFAULT_BINARY = "build/bin/libRuntimeRosettax87"

# Blob base: the runtime-routines region is a verbatim copy starting here, so
# every offset the loader needs is relative to this symbol.
BASE_SYMBOL = "_stub_far_jmp"
# End of the mapped blob; bounds the last stub's size.
END_SYMBOL = "_runtime_blob_end"


def read_symbols(binary: Path):
    """Return [(addr, name)] sorted by address, for code/data symbols."""
    try:
        out = subprocess.run(
            ["nm", "-n", str(binary)],
            capture_output=True, text=True, check=True,
        ).stdout
    except FileNotFoundError:
        sys.exit("error: `nm` not found on PATH")
    except subprocess.CalledProcessError as e:
        sys.exit(f"error: nm failed on {binary}: {e.stderr.strip()}")

    syms = []
    for line in out.splitlines():
        parts = line.split()
        # "<addr> <type> <name>"; undefined symbols have no address and are skipped.
        if len(parts) == 3 and parts[1] in "tTsSdD":
            syms.append((int(parts[0], 16), parts[2]))
    syms.sort()
    return syms


def extract(binary: Path):
    syms = read_symbols(binary)
    if not syms:
        sys.exit(f"error: no symbols in {binary} (stripped?)")

    by_name = {}
    for addr, name in syms:
        # Keep the first address for a name; duplicates would be aliases.
        by_name.setdefault(name, addr)

    if BASE_SYMBOL not in by_name:
        sys.exit(f"error: {BASE_SYMBOL} not found in {binary}")
    base = by_name[BASE_SYMBOL]
    blob_end = by_name.get(END_SYMBOL)
    if blob_end is None:
        sys.exit(f"error: {END_SYMBOL} not found in {binary}")

    addrs = [a for a, _ in syms]

    stubs = []
    for addr, name in syms:
        if not name.startswith("_stub_"):
            continue
        # Size = distance to the next symbol of any kind. Stubs are packed with
        # no padding, so the next label marks this one's end. The final stub is
        # bounded by the blob end instead.
        later = [a for a in addrs if a > addr]
        end = min(later) if later else blob_end
        stubs.append({
            "offset": addr - base,
            "size": end - addr,
            "name": name[1:],  # strip Mach-O's leading underscore
        })

    stubs.sort(key=lambda s: s["offset"])

    # Sanity: nothing may fall outside the blob, and nothing may overlap.
    span = blob_end - base
    for s in stubs:
        if not (0 <= s["offset"] < span):
            sys.exit(f"error: {s['name']} offset 0x{s['offset']:X} outside blob (span 0x{span:X})")
        if s["size"] <= 0:
            sys.exit(f"error: {s['name']} has non-positive size {s['size']}")

    return {
        "source": str(binary),
        "blob_size": span,
        "stub_count": len(stubs),
        "stubs": stubs,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("binary", nargs="?", default=DEFAULT_BINARY,
                    help=f"linked image to read (default: {DEFAULT_BINARY})")
    ap.add_argument("-o", "--output", help="write JSON here (default: stdout)")
    ap.add_argument("--python", action="store_true",
                    help="emit a Python RT_ROUTINE_STUBS literal instead of JSON")
    args = ap.parse_args()

    binary = Path(args.binary)
    if not binary.exists():
        sys.exit(f"error: {binary} not found — build libRuntimeRosettax87 first")

    data = extract(binary)

    if args.python:
        lines = ["# Generated by scripts/extract_stub_offsets.py — do not edit by hand.",
                 f"# Source: {data['source']}  blob_size=0x{data['blob_size']:X}",
                 "RT_ROUTINE_STUBS_OURS = ["]
        for s in data["stubs"]:
            lines.append(f'    (0x{s["offset"]:04X}, 0x{s["size"]:02X}, "{s["name"]}"),')
        lines.append("]")
        text = "\n".join(lines) + "\n"
    else:
        text = json.dumps(data, indent=2) + "\n"

    if args.output:
        Path(args.output).write_text(text)
        print(f"wrote {data['stub_count']} stubs to {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
